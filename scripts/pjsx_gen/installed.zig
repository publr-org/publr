//! An installed plugin's views: its own modules lowered as the compiled-in ones are, and a
//! stand-in for each component the host draws for it. A stand-in has the real component's
//! `Props` (from the generated design system the SDK carries, `ds`) and a `render` that
//! hands the props to the host (`publr.views.draw`), so no plugin carries the design system.
const std = @import("std");
const pjsx = @import("pjsx");

const Program = pjsx.targets.zig.Program;

pub const stand_ins_dir = "standins";

/// The stand-in for `name`, as Zig source.
pub fn stand_in(arena: std.mem.Allocator, name: []const u8) ![]const u8 {
    std.debug.assert(name.len > 0);
    std.debug.assert(std.ascii.isUpper(name[0]));

    return std.fmt.allocPrint(arena,
        \\//! Generated by pjsx_gen: in an installed plugin, {s} drawn by the host.
        \\const std = @import("std");
        \\const publr = @import("publr");
        \\
        \\pub const Props = @import("ds").{s}.Props;
        \\pub const root_component = @import("ds").{s}.root_component;
        \\
        \\pub fn render(writer: *std.Io.Writer, arena: std.mem.Allocator, props: Props) !void {{
        \\    return publr.views.draw(writer, arena, "{s}", Props, props);
        \\}}
        \\
    , .{ name, name, name, name });
}

/// Every stand-in, `<out>/standins/<Name>.zig`: what the SDK archive carries.
pub fn write_stand_ins(
    arena: std.mem.Allocator,
    io: std.Io,
    names: []const []const u8,
    out_dir: std.Io.Dir,
) !void {
    std.debug.assert(names.len > 0);

    try out_dir.createDirPath(io, stand_ins_dir);

    for (names) |name| {
        try out_dir.writeFile(io, .{
            .sub_path = try std.fmt.allocPrint(arena, "{s}/{s}.zig", .{ stand_ins_dir, name }),
            .data = try stand_in(arena, name),
        });
    }
}

/// The plugin's own modules, lowered, its `views.zig` naming only them, and beside them a
/// stand-in for every component it may have the host draw: `<Name>.zig`, as its modules
/// import them.
pub fn write_plugin(
    arena: std.mem.Allocator,
    io: std.Io,
    program: *Program,
    own: []const []const u8,
    callable: []const []const u8,
    out_dir: std.Io.Dir,
) !void {
    std.debug.assert(own.len > 0);
    std.debug.assert(callable.len > 0);

    var views: std.Io.Writer.Allocating = .init(arena);

    try views.writer.writeAll("//! Generated by pjsx_gen: an installed plugin's views.\n");

    for (own) |name| {
        try out_dir.writeFile(io, .{
            .sub_path = try std.fmt.allocPrint(arena, "{s}.zig", .{name}),
            .data = try program.lower(arena, name),
        });
        try views.writer.print("pub const {s} = @import(\"{s}.zig\");\n", .{ name, name });
    }

    for (callable) |name| {
        try out_dir.writeFile(io, .{
            .sub_path = try std.fmt.allocPrint(arena, "{s}.zig", .{name}),
            .data = try stand_in(arena, name),
        });
    }

    try out_dir.writeFile(io, .{
        .sub_path = "views.zig",
        .data = views.written(),
    });
}

test "a stand-in takes the real props and hands them to the host" {
    var arena_state: std.heap.ArenaAllocator = .init(std.testing.allocator);
    defer arena_state.deinit();

    const source = try stand_in(arena_state.allocator(), "IndexPage");

    const props = "@import(\"ds\").IndexPage.Props";
    const handed = "draw(writer, arena, \"IndexPage\"";

    try std.testing.expect(std.mem.indexOf(u8, source, props) != null);
    try std.testing.expect(std.mem.indexOf(u8, source, handed) != null);
}
