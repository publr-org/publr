//! A plugin's operations as TypeScript: each operation's input and output, from the shapes
//! its manifest publishes, added to `publr/operations`'s `Operations`, so `call` and `query`
//! in the plugin's views know every name and field. What `publr plugin build` writes beside
//! the views as `ui/operations.d.ts`.
const std = @import("std");
const contract = @import("contract.zig");

pub const Operation = struct {
    name: []const u8,
    input: []const contract.Node,
    output: []const contract.Node,
};

pub const header =
    \\// Generated by `publr plugin build` from this plugin's operations. Do not edit.
    \\export {};
    \\
    \\declare module "publr/operations" {
    \\  interface Operations {
    \\
;
pub const footer =
    \\  }
    \\}
    \\
;

pub fn write(
    writer: *std.Io.Writer,
    arena: std.mem.Allocator,
    operations: []const Operation,
) !void {
    std.debug.assert(operations.len <= 1024);

    try writer.writeAll(header);

    for (operations) |operation| {
        std.debug.assert(operation.name.len > 0);

        try writer.print("    \"{s}\": {{ in: {s}; out: {s} }};\n", .{
            operation.name,
            try type_of(arena, operation.input),
            try type_of(arena, operation.output),
        });
    }

    try writer.writeAll(footer);
}

/// The TypeScript for a described shape. Nodes come breadth first, every child after its
/// parent, so the last node is written first and each parent from its written children.
pub fn type_of(arena: std.mem.Allocator, nodes: []const contract.Node) ![]const u8 {
    std.debug.assert(nodes.len <= contract.nodes_max);

    if (nodes.len == 0) {
        return "unknown";
    }

    const written = try arena.alloc([]const u8, nodes.len);
    var index: u32 = @intCast(nodes.len);

    while (index > 0) {
        index -= 1;

        const base = try base_of(arena, nodes, written, index);

        written[index] = if (nodes[index].optional)
            try std.fmt.allocPrint(arena, "{s} | null", .{base})
        else
            base;
    }

    std.debug.assert(written[0].len > 0);

    return written[0];
}

fn base_of(
    arena: std.mem.Allocator,
    nodes: []const contract.Node,
    written: []const []const u8,
    index: u32,
) ![]const u8 {
    std.debug.assert(index < nodes.len);

    const node = nodes[index];

    return switch (node.kind) {
        .string, .reference => "string",
        .integer, .number => "number",
        .boolean => "boolean",
        .enumeration => try union_of(arena, node.values),
        .list => try std.fmt.allocPrint(arena, "Array<{s}>", .{
            first_child(nodes, written, index) orelse "unknown",
        }),
        .object => try object_of(arena, nodes, written, index),
    };
}

fn union_of(arena: std.mem.Allocator, values: []const []const u8) ![]const u8 {
    std.debug.assert(values.len <= 1024);

    if (values.len == 0) {
        return "string";
    }

    var out: std.Io.Writer.Allocating = .init(arena);

    for (values, 0..) |value, position| {
        const separator: []const u8 = if (position == 0) "" else " | ";

        try out.writer.print("{s}\"{s}\"", .{ separator, value });
    }

    return out.written();
}

fn first_child(nodes: []const contract.Node, written: []const []const u8, index: u32) ?[]const u8 {
    std.debug.assert(index < nodes.len);

    for (nodes[index + 1 ..], index + 1..) |node, position| {
        if (node.parent == @as(i32, @intCast(index))) {
            return written[position];
        }
    }

    return null;
}

fn object_of(
    arena: std.mem.Allocator,
    nodes: []const contract.Node,
    written: []const []const u8,
    index: u32,
) ![]const u8 {
    std.debug.assert(index < nodes.len);

    var out: std.Io.Writer.Allocating = .init(arena);
    var fields: u32 = 0;

    try out.writer.writeAll("{ ");

    for (nodes[index + 1 ..], index + 1..) |node, position| {
        if (node.parent != @as(i32, @intCast(index))) {
            continue;
        }

        const optional_mark: []const u8 = if (node.required) "" else "?";

        try out.writer.print("{s}{s}: {s}; ", .{ node.name, optional_mark, written[position] });
        fields += 1;
    }

    try out.writer.writeAll("}");

    return if (fields == 0) "Record<string, never>" else out.written();
}

test "an operation's shapes become TypeScript: optional fields, lists, enums, null" {
    var arena_state = std.heap.ArenaAllocator.init(std.testing.allocator);
    defer arena_state.deinit();
    const arena = arena_state.allocator();

    const In = struct {
        title: []const u8,
        summary: []const u8 = "",
        mood: enum { calm, angry } = .calm,
        tags: []const []const u8 = &.{},
        note: ?[]const u8 = null,
    };
    const Out = struct {
        id: []const u8,
        position: i64,
    };
    const text = try type_of(arena, comptime contract.describe(In));

    try std.testing.expectEqualStrings(
        "{ title: string; summary?: string; mood?: \"calm\" | \"angry\"; " ++
            "tags?: Array<string>; note?: string | null; }",
        text,
    );
    try std.testing.expectEqualStrings(
        "{ id: string; position: number; }",
        try type_of(arena, comptime contract.describe(Out)),
    );
    try std.testing.expectEqualStrings(
        "Record<string, never>",
        try type_of(arena, comptime contract.describe(struct {})),
    );
}

test "the module adds every operation to publr/operations' Operations" {
    var arena_state = std.heap.ArenaAllocator.init(std.testing.allocator);
    defer arena_state.deinit();
    const arena = arena_state.allocator();
    var buffer: [4096]u8 = undefined;
    var writer: std.Io.Writer = .fixed(&buffer);
    const In = struct {
        id: []const u8,
        position: i64,
    };

    try write(&writer, arena, &.{.{
        .name = "lms.move_chapter",
        .input = comptime contract.describe(In),
        .output = comptime contract.describe(struct {
            position: i64,
        }),
    }});

    const text = writer.buffered();

    const declared = "declare module \"publr/operations\"";

    try std.testing.expect(std.mem.indexOf(u8, text, declared) != null);
    try std.testing.expect(std.mem.indexOf(u8, text, "\"lms.move_chapter\": { in: { id: string; " ++
        "position: number; }; out: { position: number; } };") != null);
}
